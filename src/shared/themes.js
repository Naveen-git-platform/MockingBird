const THEME_IDS = Object.freeze(THEMES.map((t) => t.id));
const DEFAULT_THEME = 'system';

const decls = (tokens, indent) => TOKEN_NAMES.map((n) => `${indent}--${n}: ${tokens[n]};`).join('\n');

/** The full contents of src/renderer/tokens.css. */
function buildTokensCss() {
  const system = THEMES[0];
  const out = [
    '/* GENERATED by `npm run build:themes` from src/shared/themes.js. Do not edit by hand. */',
    ':root {',
    `  color-scheme: ${system.scheme};`,
    decls(system.tokens, '  '),
    '  --radius: 12px;',
    "  --mono: ui-monospace, 'Cascadia Code', 'SF Mono', Consolas, monospace;",
    '}',
    '@media (prefers-color-scheme: light) {',
    '  :root:not([data-theme]),',
    '  :root[data-theme="system"] {',
    '    color-scheme: light;',
    decls(system.lightTokens, '    '),
    '  }',
    '}',
  ];
  for (const t of THEMES.slice(1)) {
    out.push(`:root[data-theme="${t.id}"] {`, `  color-scheme: ${t.scheme};`, decls(t.tokens, '  '), '}');
  }
  return `${out.join('\n')}\n`;
}

function isTheme(id) {
  return typeof id === 'string' && THEME_IDS.includes(id);
}

/** What the settings UI needs to draw a swatch for each theme. */
function themeList() {
  return THEMES.map((t) => ({ id: t.id, label: t.label, scheme: t.scheme, swatch: [t.tokens.bg, t.tokens.surface, t.tokens.accent] }));
}

module.exports = { THEMES, THEME_IDS, DEFAULT_THEME, TOKEN_NAMES, buildTokensCss, isTheme, themeList };
